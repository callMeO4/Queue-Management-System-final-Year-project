from django.contrib.auth.models import AbstractUser
from django.db import models


class User(AbstractUser):
  """Custom User model to handle login credentials and system roles."""

  ROLE_CHOICES = (
      ('customer', 'Customer'),
      ('teller', 'Teller'),
      ('admin', 'Administrator'),
  )
  role = models.CharField(max_length=20, choices=ROLE_CHOICES, default='customer')

  def __str__(self):
    return f'{self.username} ({self.get_role_display()})'


class Customer(models.Model):
  """Stores customer information linked to a user account."""

  user = models.OneToOneField(User, on_delete=models.CASCADE)
  phone_number = models.CharField(max_length=20, blank=True, null=True)
  created_at = models.DateTimeField(auto_now_add=True)

  def __str__(self):
    return f'Customer: {self.user.username}'


class Teller(models.Model):
  """Stores teller details and availability status."""

  user = models.OneToOneField(User, on_delete=models.CASCADE)
  teller_number = models.CharField(max_length=10, unique=True)
  is_available = models.BooleanField(default=True)
  current_status_state = models.CharField(max_length=50, default='Idle')

  def __str__(self):
    return f'Teller {self.teller_number} ({self.user.get_full_name()})'


class Service(models.Model):
  """Stores available banking service categories."""

  name = models.CharField(max_length=100, unique=True)
  description = models.TextField(blank=True, null=True)
  estimated_service_duration = models.IntegerField(
      help_text='Average duration in minutes'
  )

  def __str__(self):
    return self.name


class Teller_Service(models.Model):
  """Many-to-many relationship mapping tellers to the services they can provide."""

  teller = models.ForeignKey(Teller, on_delete=models.CASCADE)
  service = models.ForeignKey(Service, on_delete=models.CASCADE)

  class Meta:
    unique_together = ('teller', 'service')

  def __str__(self):
    return f'{self.teller} -> {self.service}'


class Queue_Ticket(models.Model):
  """Stores customer queue registrations and service timestamps."""

  STATUS_CHOICES = (
      ('waiting', 'Waiting'),
      ('serving', 'Serving'),
      ('completed', 'Completed'),
      ('cancelled', 'Cancelled'),
  )

  customer = models.ForeignKey(Customer, on_delete=models.CASCADE)
  service = models.ForeignKey(Service, on_delete=models.CASCADE)
  ticket_number = models.CharField(max_length=20, unique=True)
  status = models.CharField(
      max_length=20, choices=STATUS_CHOICES, default='waiting'
  )
  registration_time = models.DateTimeField(auto_now_add=True)
  service_start_time = models.DateTimeField(blank=True, null=True)
  completion_time = models.DateTimeField(blank=True, null=True)

  def __str__(self):
    return f'Ticket {self.ticket_number} - {self.service.name}'


class Queue_Assignment(models.Model):
  """Stores teller assignments and preserves reassignment history."""

  ticket = models.ForeignKey(Queue_Ticket, on_delete=models.CASCADE)
  teller = models.ForeignKey(Teller, on_delete=models.CASCADE)
  assigned_at = models.DateTimeField(auto_now_add=True)
  is_active = models.BooleanField(default=True)

  def __str__(self):
    return f'Ticket {self.ticket.ticket_number} assigned to {self.teller}'


class Wait_Prediction(models.Model):
  """Stores waiting time predictions generated by the machine learning model."""

  ticket = models.ForeignKey(Queue_Ticket, on_delete=models.CASCADE)
  teller = models.ForeignKey(Teller, on_delete=models.CASCADE)
  predicted_wait_time = models.FloatField(
      help_text='Predicted waiting time in minutes'
  )
  created_at = models.DateTimeField(auto_now_add=True)

  def __str__(self):
    return f'Pred: {self.predicted_wait_time} mins for Ticket {self.ticket.ticket_number}'


class Notification(models.Model):
  """Stores customer notification records."""

  customer = models.ForeignKey(Customer, on_delete=models.CASCADE)
  message = models.TextField()
  is_read = models.BooleanField(default=False)
  created_at = models.DateTimeField(auto_now_add=True)

  def __str__(self):
    return f'Notification for {self.customer.user.username}'

